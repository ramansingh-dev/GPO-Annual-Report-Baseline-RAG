import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

import chromadb
import ollama


DB_PATH = PROJECT_ROOT / "chroma_db" / "gpo"
COLLECTION_NAME = "gpo_annual_report"


def main():
    question = input("Ask a question about the GPO report: ")

    # Connect to the existing vector database.
    client = chromadb.PersistentClient(path=str(DB_PATH))
    collection = client.get_collection(name=COLLECTION_NAME)

    # Convert the question into a vector using the same embedding model.
    result = ollama.embed(
        model="qwen3-embedding:0.6b",
        input=question,
    )
    question_embedding = result["embeddings"][0]

    # Find the five most similar stored chunks.
    results = collection.query(
        query_embeddings=[question_embedding],
        n_results=5,
        include=["documents", "metadatas", "distances"],
    )

    print("\nMOST RELEVANT CHUNKS")
    print("=" * 80)

    for rank, (document, metadata, distance) in enumerate(
        zip(
            results["documents"][0],
            results["metadatas"][0],
            results["distances"][0],
        ),
        start=1,
    ):
        print(f"\nResult {rank}")
        print(f"Pages: {metadata['page_start']}-{metadata['page_end']}")
        print(f"Distance: {distance:.4f}")
        print("-" * 80)
        print(document)

    print("\nRetrieval test complete. No answer was generated by an LLM.")


if __name__ == "__main__":
    main()